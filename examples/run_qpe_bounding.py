def cx_layer_patterns(circ):
    """Return Counter{CX-layer pattern: occurrences} for one circuit repetition.

    Each pattern is a frozenset of the CX pairs appearing in one ASAP layer.
    """
    patterns = Counter()

    for layer in circ.layers():
        pairs = frozenset(
            tuple(gate.qubits)
            for gate in layer
            if (
                len(gate.qubits) == 2
                and gate.name.lower() == "cx"
            )
        )

        if pairs:
            patterns[pairs] += 1

    return patterns


def exact_probability_vector(circ) -> np.ndarray:
    """Return the ideal full-register computational-basis distribution."""
    return np.asarray(
        Statevector(
            _SV._build(circ)
        ).probabilities(),
        dtype=float,
    )


def marginalize_distribution(
    probability: np.ndarray,
    n_qubits: int,
    measured_qubits,
) -> np.ndarray:
    """Marginalize a full distribution onto measured_qubits.

    The flat vector follows Qiskit's little-endian statevector indexing.
    Reshaping to [2] * n maps array axis k to qubit n - 1 - k.
    """
    measured_set = set(measured_qubits)

    drop_axes = tuple(
        n_qubits - 1 - qubit
        for qubit in range(n_qubits)
        if qubit not in measured_set
    )

    tensor = np.asarray(
        probability,
        dtype=float,
    ).reshape([2] * n_qubits)

    if drop_axes:
        tensor = tensor.sum(
            axis=drop_axes
        )

    return tensor.reshape(-1)


def measured_readout_noise(
    full_probability: np.ndarray,
    noise: NoiseModel,
    n_qubits: int,
    measured_qubits,
) -> np.ndarray:
    """Apply readout flips only to qubits measured by the QASM circuit.

    apply_readout_to_distribution applies flips to every qubit in its input,
    so first marginalize to the measured subsystem and then apply an equivalent
    NoiseModel on the reduced distribution.
    """
    measured_probability = marginalize_distribution(
        full_probability,
        n_qubits,
        measured_qubits,
    )

    return apply_readout_to_distribution(
        measured_probability,
        noise,
        len(measured_qubits),
    )


def ideal_statevector(circ) -> np.ndarray:
    """Return the ideal pure state of a proxysim circuit."""
    return np.asarray(
        Statevector(
            _SV._build(circ)
        ).data,
        dtype=complex,
    )


def state_fidelity(
    psi: np.ndarray,
    phi: np.ndarray,
) -> float:
    """Pure-state fidelity, insensitive to global phase."""
    return float(
        abs(np.vdot(psi, phi)) ** 2
    )


