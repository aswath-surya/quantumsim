def cb_cycle_worker(args):
    """Benchmark one CX-layer proxy cycle."""
    pairs, n_qubits, seed, n_decays = args

    return cycle_benchmark(
        list(pairs),
        n_qubits,
        CB_DEPTHS,
        NOISE,
        twoq="CX",
        n_decays=n_decays,
        shots=CB_SHOTS,
        seed=seed,
    )


def benchmark_cycle_patterns(
    circ,
    patterns,
    n_measured: int,
):
    """Benchmark each distinct CX-layer class needed by the QCAP bound.

    Under the homogeneous model, e_F is cached by the number of simultaneous
    CX gates in the layer. Pattern occurrence counts are retained separately.
    """
    readout_fid, readout_std = readout_fidelity(
        n_measured,
        NOISE,
        seed=3,
    )

    representative_by_size = {}

    for pattern in patterns:
        size = len(pattern)

        if size not in representative_by_size:
            representative_by_size[size] = pattern

    jobs = [
        (
            representative_by_size[size],
            circ.n_qubits,
            100 + size,
            CB_DECAYS,
        )
        for size in sorted(representative_by_size)
    ]

    results = pmap(
        cb_cycle_worker,
        jobs,
        n_workers=max(1, (os.cpu_count() or 2) - 2),
    )

    ef_by_ncx = {
        size: (
            float(result["e_F"]),
            float(result["e_F_std"]),
        )
        for size, result in zip(
            sorted(representative_by_size),
            results,
        )
    }

    counts_one_rep = {}
    cycle_efs = {}

    for index, (pattern, count) in enumerate(
        patterns.items()
    ):
        key = f"pattern_{index}"
        counts_one_rep[key] = int(count)
        cycle_efs[key] = ef_by_ncx[len(pattern)]

    return (
        counts_one_rep,
        cycle_efs,
        readout_fid,
        readout_std,
        ef_by_ncx,
    )


# =============================================================================
# Explicit-RC TVD worker
# =============================================================================

def rc_averaged_measured_tvd(args):
    """Produce one explicit-RC TVD estimate on the measured QPE register.

    Averaging order:

        trajectory mean within each RC realization
        then mean over RC realizations
        then TVD against the ideal measured distribution
    """
    (
        target,
        noise,
        ideal_measured_probability,
        measured_qubits,
        n_rc_realizations,
        n_traj_per_rc,
        seed,
    ) = args

    n_qubits = target.n_qubits

    rc_average = np.zeros_like(
        ideal_measured_probability,
        dtype=float,
    )

    for rc_index in range(n_rc_realizations):
        rc_seed = (
            seed
            + 1_000_003 * rc_index
        )

        dressed, virtual_indices = (
            explicitly_randomized_compile(
                target,
                seed=rc_seed,
            )
        )

        trajectory_rng = random.Random(
            rc_seed + 1
        )

        full_probability = np.zeros(
            2 ** n_qubits,
            dtype=float,
        )

        for _ in range(n_traj_per_rc):
            noisy_dressed = sample_trajectory(
                dressed,
                noise,
                trajectory_rng,
                virtual=virtual_indices,
            )

            state = np.asarray(
                Statevector(
                    _SV._build(noisy_dressed)
                ).data,
                dtype=complex,
            )

            full_probability += (
                np.abs(state) ** 2
            )

        full_probability /= n_traj_per_rc

        measured_probability = measured_readout_noise(
            full_probability,
            noise,
            n_qubits,
            measured_qubits,
        )

        rc_average += measured_probability

    rc_average /= n_rc_realizations

    return 0.5 * float(
        np.abs(
            rc_average
            - ideal_measured_probability
        ).sum()
    )


def scatter_summary(values) -> str:
    """Return mean and range of one raw-TVD scatter column."""
    values = np.asarray(
        values,
        dtype=float,
    )

    return (
        f"{values.mean():.5f} "
        f"[{values.min():.5f}, {values.max():.5f}]"
    )


