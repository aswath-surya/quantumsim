def validate_one_rc_realization(base_circ):
    """Check RC logical equivalence and virtual-gate reporting."""
    dressed, virtual_indices = (
        explicitly_randomized_compile(
            base_circ,
            seed=SEED,
        )
    )

    original_state = ideal_statevector(
        base_circ
    )

    dressed_state = ideal_statevector(
        dressed
    )

    fidelity = state_fidelity(
        original_state,
        dressed_state,
    )

    original_twoq = sum(
        len(gate.qubits) == 2
        for gate in base_circ.gates
    )

    dressed_twoq = sum(
        len(gate.qubits) == 2
        for gate in dressed.gates
    )

    print(
        "explicit-RC smoke test:\n"
        f"    original gates:       {len(base_circ.gates)}\n"
        f"    dressed gates:        {len(dressed.gates)}\n"
        f"    original 2q gates:    {original_twoq}\n"
        f"    dressed 2q gates:     {dressed_twoq}\n"
        f"    virtual RC gates:     {len(virtual_indices)}\n"
        f"    ideal-state fidelity: {fidelity:.12f}\n"
    )

    if not virtual_indices:
        warnings.warn(
            "pauli_twirl reported no virtual-gate indices. If Pauli dressing "
            "gates were inserted, they may be incorrectly charged physical "
            "one-qubit and idle noise.",
            RuntimeWarning,
        )

    if not np.isclose(
        fidelity,
        1.0,
        atol=1e-9,
        rtol=1e-9,
    ):
        raise RuntimeError(
            "The RC-dressed circuit is not logically equivalent to the "
            "original QPE circuit. A returned frame correction may not have "
            "been applied, or the pauli_twirl return contract differs from "
            "the forms handled by this script."
        )


