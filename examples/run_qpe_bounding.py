"""Explicit-RC QCAP bound and raw TVD scatter versus CX-cycle depth for MQT QPE.

Circuit:
    qpe11.qasm

The imported circuit contains 12 qubits:
    * 11 measured counting qubits
    * 1 unmeasured ancilla

Cycle convention
----------------
A cycle is one ASAP-parallel layer of CX gates. Distinct CX-layer patterns are
benchmarked with cycle benchmarking. Under the homogeneous synthetic noise model,
patterns containing the same number of simultaneous CX gates share one CB estimate.

For each complete-circuit repetition count d:

    logical target = U^d
    CX-cycle depth = d * number_of_CX_layers_in_U

Each raw TVD point is generated by:

    1. Constructing U^d.
    2. Generating independently randomized-compiled versions of U^d.
    3. Marking inserted Pauli dressing gates as virtual frame changes.
    4. Simulating noisy trajectories under the ORIGINAL NoiseModel.
    5. Excluding virtual frame gates from p1 and idle-noise accounting.
    6. Applying readout noise analytically.
    7. Marginalizing onto the measured counting qubits.
    8. Averaging distributions across trajectories and RC realizations.
    9. Computing TVD only after all averaging.

Because the QPE entanglers are CX gates, they are Clifford and support the full
Pauli randomized-compiling construction used by proxysim.rc.pauli_twirl.

Run:
    python examples/run_qpe_explicit_rc_bound_tvd.py
"""

